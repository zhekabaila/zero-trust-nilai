export type ReasonCode = (typeof Reason)[keyof typeof Reason];

const ALLOW_REASONS: ReadonlySet<string> = new Set([
  Reason.OWN_DATA,
  Reason.CLASS_OWNER,
  Reason.ADMIN_ALL,
  Reason.SERVICE_TOKEN,
  Reason.LOGIN_OK,
  Reason.REFRESH_OK,
  Reason.LOGOUT_OK,
  Reason.SERVICE_TOKEN_ISSUED,
  Reason.ADMIN_AUDIT_READ,
]);

export function isAllowReason(code: string): boolean {
  return ALLOW_REASONS.has(code);
}
